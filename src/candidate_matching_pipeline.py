def load_processed_jd(file_path):
    """Load the processed JD generated by jd_pipeline.py."""

    if not file_path.is_file():
        raise FileNotFoundError(
            f"Processed JD not found: {file_path}\n"
            "Run: python -m src.jd_pipeline"
        )

    with file_path.open("r", encoding="utf-8") as file:
        jd = json.load(file)

    job_title = clean_text(jd.get("job_title"))
    jd_text = clean_text(jd.get("cleaned_job_text"))

    if not jd_text:
        raise ValueError(
            "The processed JD contains no usable job description."
        )

    required_skills = jd.get("required_skills", [])
    extracted_keywords = jd.get("keywords", [])

    if not isinstance(required_skills, list):
        required_skills = split_items(required_skills)

    if not isinstance(extracted_keywords, list):
        extracted_keywords = split_items(extracted_keywords)

    required_skills = [
        clean_text(item)
        for item in required_skills
        if clean_text(item)
    ]

    extracted_keywords = [
        clean_text(item)
        for item in extracted_keywords
        if clean_text(item)
    ]

    combined_keywords = combine_unique_items(
        required_skills,
        extracted_keywords,
    )

    if not combined_keywords:
        raise ValueError(
            "No JD keywords or required skills were found."
        )

    return (
        jd,
        job_title,
        jd_text,
        combined_keywords,
        required_skills,
    )


# --------------------------------------------------
# MAIN PIPELINE
# --------------------------------------------------

def main():

    print("\n===== TALENT POOL REDISCOVERY AGENT =====")

    # Load the job description and candidate dataset.
    try:
        (
            jd,
            job_title,
            jd_text,
            jd_keywords,
            required_skills,
        ) = load_processed_jd(JD_FILE)

        candidates = load_candidates(CANDIDATE_FILE)

    except (
        FileNotFoundError,
        ValueError,
        json.JSONDecodeError,
        ImportError,
    ) as error:

        print(f"Input loading error: {error}")
        return

    print(f"Processed JD: {JD_FILE.name}")
    print(f"Job title: {job_title or 'Not specified'}")
    print(f"Domain: {jd.get('domain', 'Not specified')}")
    print(f"JD keywords and skills: {len(jd_keywords)}")
    print(f"Candidate dataset: {CANDIDATE_FILE.name}")
    print(f"Candidate records loaded: {len(candidates)}")

    missing_jd_requirements = check_missing_jd_requirements(
        jd.get("quality_check", {})
    )
    if missing_jd_requirements:
        print(
            "JD quality warning: missing required fields: "
            + ", ".join(missing_jd_requirements)
        )

    # --------------------------------------------------
    # IDENTIFY CANDIDATE DATA COLUMNS
    # --------------------------------------------------

    id_col = find_column(
        candidates,
        [
            "Candidate_ID",
            "Candidate ID",
            "Contact ID",
            "Id",
            "ID",
        ],
    )

    name_col = find_column(
        candidates,
        [
            "Candidate_Name",
            "Candidate Name",
            "Full Name",
            "Name",
        ],
    )

    title_col = find_column(
        candidates,
        [
            "Final_Job_Title",
            "Extracted_Job_Title",
            "Job Title",
            "Title",
            "Source_Title",
        ],
    )

    keyword_matched_title_col = find_column(
        candidates,
        ["CV_Keyword_Matched_Title"],
    )

    skills_col = find_column(
        candidates,
        [
            "Extracted_Skills",
            "Skills",
            "Required Skills",
            "Candidate Skills",
        ],
    )

    keywords_col = find_column(
        candidates,
        [
            "Extracted_Keywords",
            "Keywords",
            "Key Skills",
        ],
    )

    domain_col = find_column(
        candidates,
        [
            "Extracted_Domain",
            "Domain",
            "Client_Industry",
            "Industry",
        ],
    )

    experience_col = find_column(
        candidates,
        [
            "Years_of_Experience",
            "Years of Experience",
            "Experience",
        ],
    )

    qualification_col = find_column(
        candidates,
        [
            "Extracted_Qualifications",
            "Qualifications",
            "Education",
            "Degree",
        ],
    )

    # Additional fields, when available, can help semantic matching.
    profile_text_col = find_column(
        candidates,
        [
            "CV_Text",
            "Resume_Text",
            "Resume",
            "CV",
            "Candidate_Profile",
            "Profile_Text",
            "Profile_Summary",
            "Professional_Summary",
            "Description",
            "Extracted_Text",
        ],
    )

    usable_columns = [
        title_col,
        skills_col,
        keywords_col,
        domain_col,
        experience_col,
        qualification_col,
        profile_text_col,
    ]

    if not any(column is not None for column in usable_columns):
        print(
            "Cannot identify candidate information in this dataset."
        )
        print(
            "Available columns:",
            candidates.columns.tolist(),
        )
        return

    print("\nCandidate fields identified:")
    print(f"  Job title: {title_col}")
    print(f"  Title-derived keyword: {keyword_matched_title_col}")
    print(f"  Skills: {skills_col}")
    print(f"  Keywords: {keywords_col}")
    print(f"  Domain: {domain_col}")
    print(f"  Experience: {experience_col}")
    print(f"  Qualifications: {qualification_col}")
    print(f"  Profile/resume text: {profile_text_col}")

    # --------------------------------------------------
    # LOAD SEMANTIC SIMILARITY MODEL
    # --------------------------------------------------

    print("\nLoading semantic similarity model...")

    try:
        model = SentenceTransformer("all-MiniLM-L6-v2")

        jd_embedding = model.encode(
            jd_text,
            convert_to_tensor=True,
        )

    except Exception as error:
        print(f"Could not load the semantic model: {error}")
        return

    results = []
    candidates_with_profiles = 0

    # --------------------------------------------------
    # MATCH EACH CANDIDATE
    # --------------------------------------------------

    for _, candidate in candidates.iterrows():

        candidate_id = get_field(candidate, id_col)
        candidate_name = get_field(candidate, name_col)
        candidate_title = get_field(candidate, title_col)
        candidate_keyword_matched_title = get_field(
            candidate,
            keyword_matched_title_col,
        )

        candidate_skills = get_field(candidate, skills_col)
        candidate_keywords_text = get_field(
            candidate,
            keywords_col,
        )

        candidate_domain = get_field(candidate, domain_col)

        candidate_experience = get_field(
            candidate,
            experience_col,
        )

        candidate_qualifications = get_field(
            candidate,
            qualification_col,
        )

        candidate_original_profile = get_field(
            candidate,
            profile_text_col,
        )

        # Build the candidate profile using available fields.
        profile_text = make_profile_text(
            [
                candidate_title,
                candidate_skills,
                candidate_keywords_text,
                candidate_domain,
                candidate_experience,
                candidate_qualifications,
                candidate_original_profile,
            ]
        )

        # Skip candidates with no usable profile information.
        if not profile_text:
            continue

        candidates_with_profiles += 1

        # Use extracted skills and keywords for keyword scoring.
        # Do not treat the entire profile as a list of verified skills.
        extracted_keyword_items = [
            item
            for item in split_items(candidate_keywords_text)
            if not is_role_title_keyword(item)
        ]
        title_terms = {
            " ".join(value.casefold().split())
            for value in (candidate_title, candidate_keyword_matched_title)
            if value
        }
        extracted_keyword_items = [
            keyword
            for keyword in extracted_keyword_items
            if " ".join(keyword.casefold().split()) not in title_terms
        ]
        candidate_keywords = combine_unique_items(
            split_items(candidate_skills),
            extracted_keyword_items,
        )

        # Match only the candidate's skill and extracted-keyword fields.
        # Exclude role labels supplied as title-derived keywords.
        candidate_evidence_profile_text = make_profile_text(
            [
                candidate_skills,
                ", ".join(candidate_keywords),
                candidate_original_profile,
            ]
        )

        # --------------------------------------------------
        # SEMANTIC SIMILARITY
        # --------------------------------------------------

        candidate_embedding = model.encode(
            profile_text,
            convert_to_tensor=True,
        )

        semantic_similarity = float(
            util.cos_sim(
                jd_embedding,
                candidate_embedding,
            ).item()
        )

        # --------------------------------------------------
        # KEYWORD MATCHING AND FINAL SCORE
        # --------------------------------------------------

        match_result = match_candidate(
            required_skills or jd_keywords,
            candidate_keywords,
            semantic_similarity,
        )

        # --------------------------------------------------
        # DOMAIN ALIGNMENT
        # --------------------------------------------------

        required_domain = clean_text(jd.get("domain"))
        candidate_domain_clean = clean_text(candidate_domain)
        unknown_domains = {
            "",
            "unknown",
            "not specified",
            "needs review",
            "none",
            "nan",
            "null",
            "n/a",
            "na",
        }
        if (
            required_domain.casefold() in unknown_domains
            or candidate_domain_clean.casefold() in unknown_domains
        ):
            domain_match = False
            domain_match_status = "Unknown"
        elif (
            required_domain.casefold() in candidate_domain_clean.casefold()
            or candidate_domain_clean.casefold() in required_domain.casefold()
        ):
            domain_match = True
            domain_match_status = "Match"
        else:
            domain_match = False
            domain_match_status = "No match"

        # --------------------------------------------------
        # EVIDENCE, EXPLANATIONS, AND POTENTIAL GAPS
        # --------------------------------------------------

        evidence_result = explain_candidate_match(
            profile_text=candidate_evidence_profile_text,
            jd_keywords=jd_keywords,
            candidate_keywords=candidate_keywords,
            jd_quality=jd.get("quality_check", {}),
            required_skills=required_skills,
            candidate_title=candidate_title,
            candidate_experience=candidate_experience,
            candidate_qualifications=candidate_qualifications,
        )

        # --------------------------------------------------
        # STORE CANDIDATE RESULT
        # --------------------------------------------------
    
        result = {
            "Candidate_ID": candidate_id,
            "Candidate_Name": candidate_name,
            "Candidate_Title": candidate_title,
            "Candidate_Domain": (
                candidate_domain
                if candidate_domain.casefold()
                not in {"", "not specified", "needs review", "unknown"}
                else "Unknown"
            ),
            "Required_Domain": clean_text(jd.get("domain")),
            "Years_of_Experience": (
                candidate_experience
                if candidate_experience.casefold()
                not in {"", "not specified", "unknown"}
                else "Unknown"
            ),
            "Required_Experience": clean_text(
                jd.get("required_experience")
            ),
            "Qualifications": (
                candidate_qualifications
                if candidate_qualifications.casefold()
                not in {"", "not specified", "unknown"}
                else "Not verified"
            ),
            "Domain_Match": domain_match,
            "Domain_Match_Status": domain_match_status,
            "Matched_Keywords": ", ".join(
                match_result.get("matched_keywords", [])
            ),
            "Keyword_Score": match_result["keyword_score"],
            "Semantic_Similarity": (
                match_result["semantic_similarity"]
            ),
            "Final_Score": match_result["final_score"],
            **evidence_result,
        }

        results.append(result)

    # --------------------------------------------------
    # RANK CANDIDATES
    # --------------------------------------------------

    if not results:
        if candidates_with_profiles:
            print(
                "\nNo suitable candidates met the matching criteria."
            )
        else:
            print(
                "\nNo candidates had usable profile information."
            )
        return

    ranked_results = rank_candidates(results)

    evaluated_df = (
        pd.DataFrame(ranked_results)
        .sort_values("Ranking_Score", ascending=False, kind="stable")
        .reset_index(drop=True)
    )
    displayed_df = evaluated_df.loc[
        evaluated_df["Ranking_Score"] >= 40.00
    ].copy()
    displayed_df = (
        displayed_df
        .sort_values("Ranking_Score", ascending=False, kind="stable")
        .reset_index(drop=True)
    )
    displayed_ranks = range(1, len(displayed_df) + 1)
    displayed_df["Rank"] = displayed_ranks
    if "Recommendation_Status" not in displayed_df.columns:
        displayed_df["Recommendation_Status"] = "Needs Review"

    export_columns = [
        "Candidate_ID",
        "Candidate_Name",
        "Candidate_Domain",
        "Domain_Match",
        "Keyword_Score",
        "Semantic_Similarity",
        "Final_Score",
        "Matched_Keywords",
        "Evidence_Sentences",
        "Match_Explanation",
        "Missing_JD_Requirements",
        "JD_Quality_Warning",
        "Required_Experience",
        "Years_of_Experience",
        "Experience_Match_Status",
        "Recommendation_Status",
        "Recommendation_Reason",
        "Review_Flags",
        "Ranking_Explanation",
        "Recruiter_Review_Priority",
        "Domain_Match_Status",
    ]
    export_df = displayed_df[export_columns].copy()
    export_df["Rank"] = range(1, len(export_df) + 1)
    export_df["Ranking_Score_Percentage"] = displayed_df[
        "Ranking_Score"
    ].map(lambda score: f"{float(score):.2f}%")
    total_evaluated = len(evaluated_df)
    displayed_count = len(displayed_df)
    excluded_count = total_evaluated - displayed_count
    highest_displayed_score = (
        float(displayed_df["Ranking_Score"].max())
        if displayed_count
        else None
    )
    lowest_displayed_score = (
        float(displayed_df["Ranking_Score"].min())
        if displayed_count
        else None
    )

    # --------------------------------------------------
    # SAVE RESULTS
    # --------------------------------------------------

    OUTPUT_FILE.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    try:
        export_df.to_csv(
            OUTPUT_FILE,
            index=False,
            encoding="utf-8-sig",
        )

    except PermissionError:
        print(
            "\nERROR: Cannot save the results CSV. "
            "Close candidate_matching_results.csv in Excel "
            "and run the program again."
        )
        return

    # --------------------------------------------------
    # DISPLAY TOP 10 CANDIDATES
    # --------------------------------------------------

    if displayed_count:
        print("\n===== CANDIDATES MEETING 40% REVIEW SCORE THRESHOLD =====")
    else:
        print(
            "\nNo candidates met the 40.00% recruiter-review score threshold."
        )

    print(
        export_df
        .head(10)
        .to_string(index=False)
    )

    print(f"\nAll results saved to: {OUTPUT_FILE}")
    print(
        "\nRanking score is a weighted comparison index, not a "
        "probability of suitability or hiring."
    )
    print("\n===== RECRUITER-REVIEW REPORT SUMMARY =====")
    print("Total candidates evaluated:", total_evaluated)
    print("Displayed in Excel (score >= 40%):", displayed_count)
    print("Excluded from Excel (score < 40%):", excluded_count)
    if displayed_count:
        print(f"Highest displayed score: {highest_displayed_score:.2f}%")
        print(f"Lowest displayed score: {lowest_displayed_score:.2f}%")

    print(
        "\nOpen the CSV in Excel to view the explanations "
        "and potential gaps for all candidates."
    )

    print(
        "\nReminder: Potential gaps mean a requirement was not "
        "identified in the available candidate data. They do not "
        "prove that the candidate lacks that skill."
    )


if __name__ == "__main__":
    main()