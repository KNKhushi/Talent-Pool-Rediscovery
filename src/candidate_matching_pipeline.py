# HELPER FUNCTIONS
# --------------------------------------------------

def clean_text(value):
    """Convert a value to clean text and handle missing values."""

    if value is None:
        return ""

    try:
        if pd.isna(value):
            return ""
    except (TypeError, ValueError):
        pass

    text = str(value).strip()

    if text.casefold() in {"nan", "none", "null", "n/a", "na"}:
        return ""

    return text


def normalize_column_name(name):
    """Normalize column names to support naming variations."""

    return re.sub(r"[^a-z0-9]", "", str(name).lower())


def find_column(data, possible_names):
    """Find a column using alternative names."""

    normalized_columns = {
        normalize_column_name(column): column
        for column in data.columns
    }

    for name in possible_names:
        column = normalized_columns.get(
            normalize_column_name(name)
        )

        if column is not None:
            return column

    return None


def get_field(row, column):
    """Safely retrieve a candidate field."""

    if column is None:
        return ""

    return clean_text(row.get(column, ""))


def split_items(value):
    """Split comma-, semicolon-, pipe-, or line-separated values."""

    text = clean_text(value)

    if not text:
        return []

    return [
        item.strip()
        for item in re.split(r"[,;\n|]+", text)
        if item.strip()
    ]


def is_role_title_keyword(value):
    """Identify role labels that should not count as skill evidence."""
    words = clean_text(value).casefold().split()
    return bool(words) and (
        words[-1] in ROLE_TITLE_ENDINGS
        or (len(words) == 1 and words[0] in {"bookkeeper", "receptionist"})
    )


def combine_unique_items(*groups):
    """Combine lists while removing duplicate items."""

    combined = []
    seen = set()

    for group in groups:
        for item in group:
            item = clean_text(item)

            if not item:
                continue

            key = item.casefold()

            if key not in seen:
                combined.append(item)
                seen.add(key)

    return combined


def make_profile_text(values):
    """Combine available candidate information into profile text."""

    cleaned_values = []

    for value in values:
        value = clean_text(value)

        if value:
            cleaned_values.append(value)

    return " ".join(cleaned_values)


