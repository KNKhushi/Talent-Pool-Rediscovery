def load_candidates(file_path):
    """Load candidates from CSV or Excel."""

    if not file_path.is_file():
        raise FileNotFoundError(
            f"Candidate dataset not found: {file_path}"
        )

    suffix = file_path.suffix.lower()

    if suffix == ".csv":
        data = pd.read_csv(file_path)

    elif suffix in (".xlsx", ".xls"):
        data = pd.read_excel(file_path)

    else:
        raise ValueError(
            "Unsupported dataset. Use CSV, XLSX, or XLS."
        )

    if data.empty:
        raise ValueError(
            "The candidate dataset contains no records."
        )

    data.columns = [
        str(column).strip()
        for column in data.columns
    ]

    return data


